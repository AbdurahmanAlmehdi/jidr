// Generates the site's styles from the Workbench design (D41). Runs before
// `astro dev` and `astro build`; the outputs are git-ignored.
//
// - src/styles/tokens.css    every token in docs/design/tokens.json as a
//                            --jidr-* custom property (dark + light)
// - src/styles/workbench.css the component rules of docs/design/jidr.css,
//                            pruned to the classes this site's .astro files use
//
// tokens.json is the single source: no colour or size is typed here.

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const design = join(site, "../docs/design");
const out = join(site, "src/styles");

// ---- tokens.css ------------------------------------------------------------

const WEIGHT_NAMES = { 400: "regular", 500: "medium", 600: "semibold", 700: "bold" };

export function tokensCss(t) {
  const base = [];
  const dark = [];
  const light = [];
  const reduced = [];
  // DTCG aliases ({jidr-…}) become var(--jidr-…).
  const resolve = (v) => String(v).replace(/\{(jidr-[\w-]+)\}/g, "var(--$1)");
  const decl = (list, name, value) => list.push(`  --${name}: ${resolve(value)};`);

  // Fonts and type roles.
  for (const [key, family] of Object.entries(t.type.families)) {
    decl(base, `jidr-font-family-${key}`, family);
  }
  const weights = new Set();
  const arabic = t.type.groups.find((g) => g.family === "arabic");
  for (const group of t.type.groups) {
    if (group === arabic) continue;
    for (const s of group.styles) {
      weights.add(s.fontWeight);
      const p = `jidr-${s.name}`;
      decl(base, `${p}-family`, `var(--jidr-font-family-${s.family ?? group.family})`);
      decl(base, `${p}-size`, s.fontSize);
      decl(base, `${p}-weight`, s.fontWeight);
      decl(base, `${p}-line-height`, s.lineHeight);
      decl(base, `${p}-letter-spacing`, s.letterSpacing);
      if (s.name.includes("metric")) decl(base, `${p}-features`, '"tnum"');
      const ar = arabic?.styles.find((a) => a.name === `${s.name}-ar`);
      if (ar) {
        decl(base, `${p}-size-ar`, ar.fontSize);
        decl(base, `${p}-line-height-ar`, ar.lineHeight);
      }
    }
  }
  for (const w of [...weights].sort()) {
    if (WEIGHT_NAMES[w]) decl(base, `jidr-font-weight-${WEIGHT_NAMES[w]}`, w);
  }

  // Colours, then every other group. Themed values ({dark, light}) go to the
  // theme blocks; shadows also expose their colour, y and blur parts.
  const groups = [t.color, ...Object.entries(t)
    .filter(([k, v]) => !["color", "type"].includes(k) && v && Array.isArray(v.tokens))
    .map(([, v]) => v)];
  for (const group of groups) {
    for (const tok of group.tokens) {
      const themed = typeof tok.value === "object";
      for (const [list, theme] of themed ? [[dark, "dark"], [light, "light"]] : [[base, null]]) {
        const value = theme ? tok.value[theme] : tok.value;
        decl(list, tok.name, value);
        if (tok.name.endsWith("-shadow")) {
          const [, y, blur, , color] = String(value).split(/\s+/);
          decl(list, `${tok.name}-color`, color);
          decl(list, `${tok.name}-y`, y);
          decl(list, `${tok.name}-blur`, blur);
        }
      }
      // Reduce Motion, from each motion token's own "Reduced:" note.
      const note = /Reduced:\s*([^.]*)/.exec(tok.usage ?? "")?.[1]?.toLowerCase();
      if (tok.name.startsWith("jidr-motion-") && note) {
        if (tok.name.endsWith("-distance")) decl(reduced, tok.name, "0px");
        else if (/instant|jumps|static/.test(note)) decl(reduced, tok.name, "0ms");
      }
    }
  }

  const block = (sel, lines, scheme) =>
    `${sel} {\n${scheme ? `  color-scheme: ${scheme};\n` : ""}${lines.join("\n")}\n}`;
  return [
    "/* Generated by site/scripts/build-styles.mjs from docs/design/tokens.json. Don't edit. */",
    block(":root", base),
    block(":root,\n.jidr-dark", dark, "dark"),
    `@media (prefers-color-scheme: light) {\n${block(':root:not([data-theme="dark"])', light, "light")}\n}`,
    block(':root[data-theme="light"],\n.jidr-light', light, "light"),
    block(':root[data-theme="dark"]', dark, "dark"),
    reduced.length ? `@media (prefers-reduced-motion: reduce) {\n${block(":root", reduced)}\n}` : "",
  ].join("\n\n") + "\n";
}

// ---- workbench.css -----------------------------------------------------------

/** Splits CSS into top-level nodes: rules and at-rules (with children for
 * @media/@container/@supports). Comments are dropped. */
export function parseCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const nodes = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) break;
    const prelude = css.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") depth--;
      j++;
    }
    const body = css.slice(open + 1, j - 1);
    if (/^@(media|container|supports)\b/.test(prelude)) {
      nodes.push({ at: prelude, children: parseCss(body) });
    } else if (prelude.startsWith("@")) {
      nodes.push({ at: prelude, raw: body });
    } else if (prelude) {
      nodes.push({ selector: prelude, body: body.trim() });
    }
    i = j;
  }
  return nodes;
}

function splitSelectors(selector) {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (const ch of selector) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

/** Keeps the selectors whose classes are all in `used` (class-free selectors
 * stay); drops rules left with none, and @keyframes nothing animates. */
export function prune(nodes, used) {
  const keep = (sel) => {
    const classes = sel.replace(/:not\([^)]*\)/g, "").match(/\.[A-Za-z_][\w-]*/g) ?? [];
    return classes.every((c) => used.has(c.slice(1)));
  };
  const walk = (list) =>
    list.flatMap((n) => {
      if (n.children) {
        const children = walk(n.children);
        return children.length ? [{ ...n, children }] : [];
      }
      if (n.raw !== undefined) return [n];
      const sels = splitSelectors(n.selector).filter(keep);
      return sels.length ? [{ ...n, selector: sels.join(",") }] : [];
    });
  const kept = walk(nodes);
  const text = print(kept.filter((n) => !n.at?.startsWith("@keyframes")));
  return kept.filter((n) => {
    const name = /^@keyframes\s+([\w-]+)/.exec(n.at ?? "")?.[1];
    return !name || text.includes(name);
  });
}

export function print(nodes) {
  return nodes
    .map((n) =>
      n.children
        ? `${n.at}{\n${print(n.children)}\n}`
        : n.raw !== undefined
          ? `${n.at}{${n.raw}}`
          : `${n.selector}{${n.body}}`,
    )
    .join("\n");
}

/** Every class named in a `class="…"` attribute of the site's .astro files. */
export function usedClasses(dir) {
  const used = new Set();
  const visit = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) visit(p);
      else if (e.name.endsWith(".astro")) {
        for (const m of readFileSync(p, "utf8").matchAll(/\bclass="([^"]*)"/g)) {
          for (const c of m[1].split(/\s+/)) if (/^[A-Za-z_][\w-]*$/.test(c)) used.add(c);
        }
      }
    }
  };
  visit(dir);
  return used;
}

const MARKER = "/* ===================================================================== page chrome */";

function main() {
  mkdirSync(out, { recursive: true });
  const tokens = JSON.parse(readFileSync(join(design, "tokens.json"), "utf8"));
  const jidrCss = readFileSync(join(design, "jidr.css"), "utf8");
  writeFileSync(join(out, "tokens.css"), tokensCss(tokens));

  const at = jidrCss.indexOf(MARKER);
  if (at === -1) throw new Error(`jidr.css no longer has the "${MARKER}" marker`);
  const used = usedClasses(join(site, "src"));
  const css = print(prune(parseCss(jidrCss.slice(at)), used));
  writeFileSync(
    join(out, "workbench.css"),
    `/* Generated by site/scripts/build-styles.mjs: the component rules of\n   docs/design/jidr.css that this site uses. Don't edit. */\n${css}\n`,
  );
  console.log(
    `build-styles: ${relative(site, join(out, "tokens.css"))}, ${relative(site, join(out, "workbench.css"))} (${used.size} classes)`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
