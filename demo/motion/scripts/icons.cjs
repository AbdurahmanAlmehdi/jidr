// Regenerates src/icons.ts from the app's Lucide icons (crates/jidr-ui/ui/icons).
// Run from demo/motion: node scripts/icons.cjs
const fs = require('fs');
const path = require('path');
const dir = path.resolve(__dirname, '../../../crates/jidr-ui/ui/icons');
const names = [
  'arrow-left', 'badge-check', 'camera', 'check', 'chevron-down', 'circle', 'circle-dot', 'clipboard',
  'clock', 'download', 'ellipsis', 'key-round', 'layout-grid', 'loader-circle', 'minus', 'panel-left',
  'panel-right', 'play', 'plus', 'power', 'rotate-ccw', 'rotate-cw', 'scan', 'scroll-text', 'search',
  'shield-alert', 'sliders-horizontal', 'smartphone', 'square', 'terminal', 'undo-2', 'volume-1',
  'volume-2', 'x',
];
let out = '// Generated by scripts/icons.cjs from crates/jidr-ui/ui/icons (Lucide, ISC: see LICENSE-lucide.txt).\n';
out += 'export const ICONS: Record<string, string> = {\n';
for (const n of names) {
  const s = fs.readFileSync(path.join(dir, `${n}.svg`), 'utf8');
  const inner = s.replace(/^[\s\S]*?<svg[\s\S]*?>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  out += `  '${n}': ${JSON.stringify(inner)},\n`;
}
out += '};\n';
fs.writeFileSync(path.resolve(__dirname, '../src/icons.ts'), out);
