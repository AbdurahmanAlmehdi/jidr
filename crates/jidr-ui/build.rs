//! Generates `ui/theme.slint` from `docs/design/tokens.json` (D41: one
//! source, never hand-copied hex), compiles the Slint UI with the bundled
//! translations, and turns the same catalogs into the table `src/i18n.rs`
//! reads for the strings Rust builds.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::Value;

type Res<T> = Result<T, Box<dyn std::error::Error>>;

fn main() -> Res<()> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let design = manifest.join("../../docs/design");
    let tokens = design.join("tokens.json");
    let bundle = design.join("system/components/bundle.css");
    println!("cargo:rerun-if-changed={}", tokens.display());
    println!("cargo:rerun-if-changed={}", bundle.display());

    write_if_changed(
        &manifest.join("ui/theme.slint"),
        &generate_theme(&tokens, &bundle)?,
    )?;
    let icons = manifest.join("ui/icons");
    println!("cargo:rerun-if-changed={}", icons.display());
    write_if_changed(&manifest.join("ui/icons.slint"), &generate_icons(&icons)?)?;

    let i18n = manifest.join("i18n");
    println!("cargo:rerun-if-changed={}", i18n.display());
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(out.join("i18n_catalog.rs"), generate_catalog(&i18n)?)?;

    // No default context: one msgid has one translation wherever it appears,
    // and the Rust side (which has no component names) shares the catalog.
    let config = slint_build::CompilerConfiguration::new()
        .with_style("fluent".into())
        .with_bundled_translations(&i18n)
        .with_default_translation_context(slint_build::DefaultTranslationContext::None);
    slint_build::compile_with_config(manifest.join("ui/app.slint"), config)?;
    Ok(())
}

/// `PLURAL_FORMS` and `CATALOG` (per language, translated entries sorted
/// by msgid) from `i18n/<lang>/LC_MESSAGES/jidr-ui.po`.
fn generate_catalog(dir: &Path) -> Res<String> {
    use rspolib::TranslatedEntry as _;
    let mut langs: Vec<(String, PathBuf)> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok())
        .map(|e| {
            (
                e.file_name().to_string_lossy().into_owned(),
                e.path().join("LC_MESSAGES/jidr-ui.po"),
            )
        })
        .filter(|(_, p)| p.exists())
        .collect();
    langs.sort();
    let mut forms = String::from(
        "/// Each catalog's `Plural-Forms` (checked against `Lang::plural` in a test).\n#[cfg_attr(not(test), allow(dead_code))]\npub(super) static PLURAL_FORMS: &[(&str, &str)] = &[\n",
    );
    let mut cat = String::from(
        "/// msgid → msgstr forms, sorted by msgid.\npub(super) type Entries = &'static [(&'static str, &'static [&'static str])];\npub(super) static CATALOG: &[(&str, Entries)] = &[\n",
    );
    for (lang, path) in langs {
        let po = rspolib::pofile(path.as_path()).map_err(|e| format!("{}: {e}", path.display()))?;
        let pf = po.metadata.get("Plural-Forms").cloned().unwrap_or_default();
        writeln!(forms, "    ({lang:?}, {pf:?}),")?;
        let mut entries: Vec<(String, Vec<String>)> = po
            .entries
            .iter()
            .filter(|e| e.translated() && !e.fuzzy() && e.msgctxt.is_none())
            .map(|e| {
                let strs = if e.msgid_plural.is_some() {
                    e.msgstr_plural.clone()
                } else {
                    e.msgstr.iter().cloned().collect()
                };
                (e.msgid.clone(), strs)
            })
            .collect();
        entries.sort_by(|a, b| a.0.cmp(&b.0));
        entries.dedup_by(|a, b| a.0 == b.0);
        writeln!(cat, "    ({lang:?}, &[")?;
        for (id, strs) in entries {
            writeln!(cat, "        ({id:?}, &{strs:?}),")?;
        }
        writeln!(cat, "    ]),")?;
    }
    forms.push_str("];\n");
    cat.push_str("];\n");
    Ok(format!("{forms}{cat}"))
}

fn write_if_changed(path: &Path, text: &str) -> Res<()> {
    if std::fs::read_to_string(path).ok().as_deref() != Some(text) {
        std::fs::write(path, text)?;
    }
    Ok(())
}

/// `export global Icons` with one `@image-url` per Lucide SVG in `ui/icons/`.
fn generate_icons(dir: &Path) -> Res<String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            e.file_name()
                .to_str()
                .and_then(|n| n.strip_suffix(".svg"))
                .map(str::to_string)
        })
        .collect();
    names.sort();
    let mut s = String::from(
        "// Generated by crates/jidr-ui/build.rs from ui/icons/*.svg (Lucide, ISC). Do not edit.\n\nexport global Icons {\n",
    );
    for n in names {
        writeln!(
            s,
            "    out property <image> {n}: @image-url(\"icons/{n}.svg\");"
        )?;
    }
    s.push_str("}\n");
    Ok(s)
}

/// `jidr-color-surface-raised` → `surface-raised`; other paths keep their
/// group (`jidr-space-sm` → `space-sm`).
fn slint_name(token: &str) -> String {
    let n = token.strip_prefix("jidr-").unwrap_or(token);
    n.strip_prefix("color-").unwrap_or(n).to_string()
}

struct Tokens {
    /// name → (dark, light) raw values.
    themed: BTreeMap<String, (String, String)>,
}

impl Tokens {
    /// Resolves `{jidr-…}` references (one level is all the file uses, but
    /// follow chains anyway).
    fn resolve(&self, v: &str, dark: bool) -> String {
        let mut v = v.to_string();
        for _ in 0..8 {
            let Some(r) = v.strip_prefix('{').and_then(|s| s.strip_suffix('}')) else {
                break;
            };
            match self.themed.get(r) {
                Some((d, l)) => v = if dark { d.clone() } else { l.clone() },
                None => break,
            }
        }
        v
    }
}

fn str_of(v: &Value, key: &str) -> Res<String> {
    v.get(key)
        .and_then(Value::as_str)
        .map(str::to_string)
        .ok_or_else(|| format!("token without string `{key}`: {v}").into())
}

fn generate_theme(tokens_path: &Path, bundle_css: &Path) -> Res<String> {
    let root: Value = serde_json::from_str(&std::fs::read_to_string(tokens_path)?)?;
    let mut themed = BTreeMap::new();
    let mut plain: Vec<(String, String)> = Vec::new();
    for group in [
        "color", "shadow", "spacing", "radius", "border", "size", "frame", "density", "layout",
        "duration", "easing",
    ] {
        let list = root
            .get(group)
            .and_then(|g| g.get("tokens"))
            .and_then(Value::as_array)
            .ok_or_else(|| format!("tokens.json: no `{group}.tokens`"))?;
        for t in list {
            let name = str_of(t, "name")?;
            match t.get("value") {
                Some(Value::Object(m)) => {
                    let d = m.get("dark").and_then(Value::as_str).unwrap_or_default();
                    let l = m.get("light").and_then(Value::as_str).unwrap_or_default();
                    themed.insert(name, (d.to_string(), l.to_string()));
                }
                Some(Value::String(s)) => plain.push((name, s.clone())),
                _ => return Err(format!("token {name}: unexpected value").into()),
            }
        }
    }
    let tokens = Tokens { themed };
    let reduced = reduced_motion(&std::fs::read_to_string(bundle_css)?);

    let mut s = String::new();
    let mut easings = String::new();
    writeln!(
        s,
        "// Generated by crates/jidr-ui/build.rs from docs/design/tokens.json. Do not edit."
    )?;
    writeln!(
        s,
        "// Dark and light values side by side; `dark` picks one."
    )?;
    writeln!(s)?;
    writeln!(s, "export global Theme {{")?;
    writeln!(s, "    in-out property <bool> dark: true;")?;
    writeln!(
        s,
        "    /// Mirrors layouts for right-to-left scripts (D33). Logcat, code and the Android screen never mirror."
    )?;
    writeln!(s, "    in-out property <bool> rtl: false;")?;
    writeln!(
        s,
        "    /// Arabic text: `font-ui` becomes Noto Kufi Arabic (Latin words included, as on the site) and the type roles take their `-ar` sizes."
    )?;
    writeln!(s, "    in-out property <bool> arabic: false;")?;
    writeln!(
        s,
        "    /// macOS Reduce Motion: motion-* durations switch to their reduced values."
    )?;
    writeln!(s, "    in-out property <bool> reduce-motion: false;")?;
    writeln!(s)?;

    for (name, (d, l)) in &tokens.themed {
        let id = slint_name(name);
        if name.ends_with("-shadow") {
            let (dy, blur, dc) = parse_shadow(&tokens.resolve(d, true))?;
            let (ly, lblur, lc) = parse_shadow(&tokens.resolve(l, false))?;
            writeln!(
                s,
                "    out property <length> {id}-y: dark ? {dy} : {ly};\n    out property <length> {id}-blur: dark ? {blur} : {lblur};\n    out property <color> {id}-color: dark ? {dc} : {lc};"
            )?;
            continue;
        }
        let dv = color(&tokens.resolve(d, true))?;
        let lv = color(&tokens.resolve(l, false))?;
        writeln!(s, "    out property <color> {id}: dark ? {dv} : {lv};")?;
    }
    writeln!(s)?;
    for (name, v) in &plain {
        let id = slint_name(name);
        if let Some(ms) = v.strip_suffix("ms") {
            match reduced.get(name.as_str()) {
                Some(r) => writeln!(
                    s,
                    "    out property <duration> {id}: reduce-motion ? {r} : {ms}ms;"
                )?,
                None => writeln!(s, "    out property <duration> {id}: {ms}ms;")?,
            }
        } else if v.ends_with("px") {
            match reduced.get(name.as_str()) {
                Some(r) => writeln!(
                    s,
                    "    out property <length> {id}: reduce-motion ? {r} : {v};"
                )?,
                None => writeln!(s, "    out property <length> {id}: {v};")?,
            }
        } else if v.starts_with("cubic-bezier(") {
            // Easing can't cross into Rust, so it lives in its own global.
            writeln!(easings, "    out property <easing> {id}: {v};")?;
        } else {
            return Err(format!("token {name}: unknown unit in {v}").into());
        }
    }
    writeln!(s)?;

    let families = root
        .get("type")
        .and_then(|t| t.get("families"))
        .ok_or("tokens.json: no type.families")?;
    for key in ["ui", "mono", "arabic"] {
        let stack = str_of(families, key)?;
        let first = stack
            .split(',')
            .next()
            .unwrap_or_default()
            .trim()
            .trim_matches('"');
        if key == "ui" {
            let ar = str_of(families, "arabic")?;
            let ar = ar
                .split(',')
                .next()
                .unwrap_or_default()
                .trim()
                .trim_matches('"');
            writeln!(
                s,
                "    out property <string> font-ui: arabic ? \"{ar}\" : \"{first}\";"
            )?;
        } else {
            writeln!(s, "    out property <string> font-{key}: \"{first}\";")?;
        }
    }
    let groups = root
        .get("type")
        .and_then(|t| t.get("groups"))
        .and_then(Value::as_array)
        .ok_or("tokens.json: no type.groups")?;
    // name → (size, line height, letter spacing); the Arabic roles
    // (`type-body-ar`, …) replace their Latin twins while `arabic` is on.
    let mut metrics: BTreeMap<String, (String, String, String)> = BTreeMap::new();
    for g in groups {
        for st in g
            .get("styles")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            metrics.insert(
                str_of(st, "name")?,
                (
                    str_of(st, "fontSize")?,
                    str_of(st, "lineHeight")?,
                    str_of(st, "letterSpacing")?,
                ),
            );
        }
    }
    for g in groups {
        let gfamily = str_of(g, "family")?;
        for st in g
            .get("styles")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            let id = str_of(st, "name")?;
            let family = st
                .get("family")
                .and_then(Value::as_str)
                .unwrap_or(&gfamily)
                .to_string();
            let weight = st.get("fontWeight").and_then(Value::as_i64).unwrap_or(400);
            let (size, lh, ls) = metrics.get(&id).cloned().unwrap_or_default();
            let pick = |latin: &str, ar: Option<&str>| match ar {
                Some(ar) if ar != latin => format!("arabic ? {ar} : {latin}"),
                _ => latin.to_string(),
            };
            let ar = metrics.get(&format!("{id}-ar"));
            writeln!(
                s,
                "    out property <length> {id}-size: {};\n    out property <length> {id}-line-height: {};\n    out property <int> {id}-weight: {weight};\n    out property <length> {id}-letter-spacing: {};\n    out property <string> {id}-family: font-{family};",
                pick(&size, ar.map(|a| a.0.as_str())),
                pick(&lh, ar.map(|a| a.1.as_str())),
                pick(&ls, ar.map(|a| a.2.as_str())),
            )?;
        }
    }
    writeln!(s, "}}")?;
    writeln!(s)?;
    writeln!(s, "export global Easing {{")?;
    s.push_str(&easings);
    writeln!(s, "}}")?;
    Ok(s)
}

/// `#rrggbb` / `#rrggbbaa` → a Slint colour literal (validated).
fn color(v: &str) -> Res<String> {
    let hex = v
        .strip_prefix('#')
        .ok_or_else(|| format!("not a colour: {v}"))?;
    if !(hex.len() == 6 || hex.len() == 8) || !hex.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err(format!("not a colour: {v}").into());
    }
    Ok(format!("#{}", hex.to_ascii_lowercase()))
}

/// `0px 6px 16px 0px #12151A24` → (y, blur, colour).
fn parse_shadow(v: &str) -> Res<(String, String, String)> {
    let parts: Vec<&str> = v.split_whitespace().collect();
    match parts.as_slice() {
        [_x, y, blur, _spread, c] => Ok((y.to_string(), blur.to_string(), color(c)?)),
        _ => Err(format!("bad shadow: {v}").into()),
    }
}

/// The `prefers-reduced-motion` overrides from the generated `bundle.css`.
fn reduced_motion(css: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let Some(start) = css.find("prefers-reduced-motion: reduce") else {
        return out;
    };
    let block = &css[start..];
    let end = block.find("}\n}").unwrap_or(block.len());
    for line in block[..end].lines() {
        let line = line.trim().trim_end_matches(';');
        if let Some((k, v)) = line.split_once(':')
            && let Some(name) = k.trim().strip_prefix("--")
        {
            out.insert(name.to_string(), v.trim().to_string());
        }
    }
    out
}
